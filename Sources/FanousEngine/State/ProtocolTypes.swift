import Foundation
import FanousCore

/// Emits `web/src/lib/protocol.d.ts` from the command registry (DESIGN.md §11.4) so client and server
/// cannot drift; `scripts/check-protocol-dts.sh` compares it in CI like the channel map.
public enum ProtocolTypes {
    public static func typescript(commands: [CommandSpec]) -> String {
        var out = """
            // SPDX-License-Identifier: GPL-3.0-only
            // Copyright (c) 2026 Tim de Bruijn
            // Additional terms under GPLv3 §7 apply: see LICENSE-ADDITIONAL-TERMS.md
            // Generated by `fanousd protocol-dts` from FanousEngine's command registry; do not edit by hand.
            // Transport: WSS \(StateServer.path) on the engine's HTTPS port (DESIGN.md §11.2), JSON text frames plus
            // binary frames `[u8 kind][u32 streamId][payload]` (kind 1 = H.264 AU, 2 = JPEG, 3 = DMX universe, 4 = metrics).

            export type Role = \(Role.allCases.map { "'\($0.rawValue)'" }.joined(separator: " | "));

            export type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };

            export interface PatchOp {
              op: 'add' | 'remove' | 'replace';
              path: string;
              value?: JSONValue;
            }

            export type CommandName =
            \(commands.map { "  | '\($0.name)'" }.joined(separator: "\n"));

            export interface CommandArgs {
            \(commands.map { "  /** \($0.summary) Role: \($0.role.rawValue)\($0.mutatesConfig ? ", refused under show lock" : "")\($0.undoable ? ", undoable" : ""). */\n  '\($0.name)': \($0.argsType);" }.joined(separator: "\n"))
            }

            export type ClientMessage =
              | { t: 'hello'; clientId: string; schema: \(StateServer.schema); role?: Role; token?: string }
              | { t: 'cmd'; id: string; name: CommandName; args?: JSONValue }
              | { t: 'snapshot' }
              | { t: 'sub'; stream: 'dmx'; universe: string }
              | { t: 'sub'; stream: 'preview'; codec?: 'avc' | 'jpeg'; target?: string }
              | { t: 'unsub'; id: number };

            export type ServerMessage =
              | { t: 'welcome'; role: Role; rev: number; project: JSONValue; live: JSONValue; caps: JSONValue }
              | { t: 'snapshot'; rev: number; project: JSONValue; live: JSONValue }
              | { t: 'patch'; rev: number; doc: 'project' | 'live'; ops: PatchOp[] }
              | { t: 'ack'; id: string; ok: true; rev: number; result: JSONValue }
              | { t: 'ack'; id: string; ok: false; error: { code: string; message: string } }
              | { t: 'sub'; id: number; stream: 'dmx'; universe: string }
              | { t: 'sub'; id: number; stream: 'preview'; codec: 'avc' | 'jpeg'; w: number; h: number; fps: number; target: string }
              | { t: 'stream'; id: number; codec: string; description: string; w: number; h: number; fps: number }
              | { t: 'error'; code: string; message: string };

            /** Binary frame kind 1 (H.264): `[u8 key][u64 be timestamp µs][AVCC access unit]` after the 5-byte stream header; kind 2 (JPEG): the file; kind 3 (DMX): 512 slot bytes. */

            """
        out = out.replacingOccurrences(of: "\n            ", with: "\n")
        return out
    }
}
