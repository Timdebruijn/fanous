import CryptoKit
import Foundation
import LanthornCore
import Logging
import Security

public enum TLSIdentityError: Error, CustomStringConvertible {
    case security(OSStatus, String)
    case cf(Error, String)
    case invalidKey

    public var description: String {
        switch self {
        case .security(let status, let what):
            let message = SecCopyErrorMessageString(status, nil) as String? ?? "OSStatus \(status)"
            return "\(what): \(message)"
        case .cf(let error, let what): return "\(what): \(error)"
        case .invalidKey: return "unexpected public key encoding"
        }
    }
}

/// The server's TLS identity: an ECDSA P-256 key in the login keychain and a
/// self-signed certificate generated by LanthornCore's X.509 writer.
/// ponytail: login keychain + item label; the data-protection keychain needs
/// a team-signed binary, revisit when the Developer ID build exists (R6).
public struct TLSIdentity: @unchecked Sendable {
    public static let label = "Lanthorn TLS"
    static let keyTag = Data("org.lanthorn.tls".utf8)

    public let identity: SecIdentity
    public let certificateDER: Data
    public var fingerprintSHA256: String { SHA256.hash(data: certificateDER).map { String(format: "%02x", $0) }.joined() }

    public static func loadOrCreate(directory: URL, hostnames: [String], ipAddresses: [String], logger: Logger) throws
        -> TLSIdentity
    {
        if let existing = try load(from: directory) {
            logger.info("TLS identity loaded", metadata: ["sha256": "\(existing.fingerprintSHA256)"])
            return existing
        }
        let created = try create(hostnames: hostnames, ipAddresses: ipAddresses)
        try created.export(to: directory)
        logger.info(
            "TLS identity created",
            metadata: ["sha256": "\(created.fingerprintSHA256)", "hostnames": "\(hostnames)", "ips": "\(ipAddresses)"])
        return created
    }

    /// Writes the public certificate and its fingerprint for the shell to pin.
    public func export(to directory: URL) throws {
        try certificateDER.write(to: directory.appending(path: "certificate.der"), options: .atomic)
        try Data((fingerprintSHA256 + "\n").utf8).write(to: directory.appending(path: "fingerprint.sha256"), options: .atomic)
    }

    /// The certificate is re-read from `certificate.der`; the keychain finds
    /// the matching private key by public-key hash. (macOS sets a
    /// certificate's keychain label from its CN, so a label lookup is unreliable.)
    static func load(from directory: URL) throws -> TLSIdentity? {
        guard let der = try? Data(contentsOf: directory.appending(path: "certificate.der")),
            let certificate = SecCertificateCreateWithData(nil, der as CFData)
        else { return nil }
        var identity: SecIdentity?
        let status = SecIdentityCreateWithCertificate(nil, certificate, &identity)
        guard status == errSecSuccess, let identity else { return nil }  // key gone: regenerate
        return TLSIdentity(identity: identity, certificateDER: der)
    }

    static func identity(for certificate: SecCertificate) throws -> TLSIdentity {
        var identity: SecIdentity?
        let status = SecIdentityCreateWithCertificate(nil, certificate, &identity)
        guard status == errSecSuccess, let identity else { throw TLSIdentityError.security(status, "create identity") }
        return TLSIdentity(identity: identity, certificateDER: SecCertificateCopyData(certificate) as Data)
    }

    static func create(hostnames: [String], ipAddresses: [String]) throws -> TLSIdentity {
        let attributes: [String: Any] = [
            kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
            kSecAttrKeySizeInBits as String: 256,
            kSecAttrLabel as String: label,
            kSecPrivateKeyAttrs as String: [
                kSecAttrIsPermanent as String: true,
                kSecAttrApplicationTag as String: keyTag,
            ],
        ]
        var error: Unmanaged<CFError>?
        guard let privateKey = SecKeyCreateRandomKey(attributes as CFDictionary, &error) else {
            throw TLSIdentityError.cf(error!.takeRetainedValue(), "generate key")
        }
        guard let publicKey = SecKeyCopyPublicKey(privateKey),
            let publicData = SecKeyCopyExternalRepresentation(publicKey, &error) as Data?
        else { throw TLSIdentityError.cf(error!.takeRetainedValue(), "export public key") }
        guard publicData.count == 65, publicData.first == 0x04 else { throw TLSIdentityError.invalidKey }

        var serial = (0..<16).map { _ in UInt8.random(in: 0...255) }
        serial[0] &= 0x7F
        let now = Date()
        let template = X509SelfSignedCertificate(
            commonName: "Lanthorn (\(hostnames.first ?? "server"))",
            serialNumber: serial,
            notBefore: now.addingTimeInterval(-300),
            notAfter: now.addingTimeInterval(10 * 365 * 86_400),
            publicKeyX963: Array(publicData),
            dnsNames: hostnames,
            ipAddresses: ipAddresses.compactMap(ipBytes))
        let tbs = Data(template.tbsCertificate())
        guard let signature = SecKeyCreateSignature(privateKey, .ecdsaSignatureMessageX962SHA256, tbs as CFData, &error) as Data?
        else { throw TLSIdentityError.cf(error!.takeRetainedValue(), "sign certificate") }
        let der = Data(template.certificate(signature: Array(signature)))
        guard let certificate = SecCertificateCreateWithData(nil, der as CFData) else {
            throw TLSIdentityError.security(errSecDecode, "parse generated certificate")
        }
        let add: [String: Any] = [
            kSecClass as String: kSecClassCertificate,
            kSecValueRef as String: certificate,
            kSecAttrLabel as String: label,
        ]
        let status = SecItemAdd(add as CFDictionary, nil)
        guard status == errSecSuccess || status == errSecDuplicateItem else {
            throw TLSIdentityError.security(status, "store certificate")
        }
        return try identity(for: certificate)
    }

    static func ipBytes(_ text: String) -> [UInt8]? {
        var v4 = in_addr()
        if inet_pton(AF_INET, text, &v4) == 1 { return withUnsafeBytes(of: &v4) { Array($0) } }
        var v6 = in6_addr()
        if inet_pton(AF_INET6, text, &v6) == 1 { return withUnsafeBytes(of: &v6) { Array($0) } }
        return nil
    }
}
