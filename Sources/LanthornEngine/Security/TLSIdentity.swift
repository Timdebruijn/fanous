import CryptoKit
import Foundation
import LanthornCore
import Logging
import Security

public enum TLSIdentityError: Error, CustomStringConvertible {
    case security(OSStatus, String)
    case cf(Error, String)
    case invalidKey

    public var description: String {
        switch self {
        case .security(let status, let what):
            let message = SecCopyErrorMessageString(status, nil) as String? ?? "OSStatus \(status)"
            return "\(what): \(message)"
        case .cf(let error, let what): return "\(what): \(error)"
        case .invalidKey: return "unexpected public key encoding"
        }
    }
}

/// The server's TLS identity: an ECDSA P-256 key and a self-signed certificate
/// generated by LanthornCore's X.509 writer.
///
/// Storage (OPEN-26, decided in Phase 3): signed builds keep the key in the
/// data-protection keychain (no prompts, bound to the application identifier).
/// Builds without a team identifier (ad-hoc development builds) cannot use
/// that keychain, and the login keychain prompts whenever the binary changes
/// (risk R6), so they keep the key in `private-key.der` (mode 0600) and build
/// the identity in memory with `SecIdentityCreate`. The login keychain is
/// never consulted.
public struct TLSIdentity: @unchecked Sendable {
    public enum Storage: String, Sendable { case dataProtectionKeychain, file }

    public static let label = "Lanthorn TLS"
    static let keyTag = Data("org.lanthorn.tls".utf8)
    static var keyAttributes: [String: Any] { [
        kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
        kSecAttrKeyClass as String: kSecAttrKeyClassPrivate,
        kSecAttrKeySizeInBits as String: 256,
    ] }

    public let identity: SecIdentity
    public let certificateDER: Data
    public var storage: Storage = .file
    public var fingerprintSHA256: String { SHA256.hash(data: certificateDER).map { String(format: "%02x", $0) }.joined() }

    public static func loadOrCreate(directory: URL, hostnames: [String], ipAddresses: [String], logger: Logger) throws
        -> TLSIdentity
    {
        if let existing = try load(from: directory) {
            logger.info("TLS identity loaded", metadata: ["sha256": "\(existing.fingerprintSHA256)", "storage": "\(existing.storage.rawValue)"])
            return existing
        }
        let created = try create(hostnames: hostnames, ipAddresses: ipAddresses, directory: directory)
        try created.export(to: directory)
        logger.info(
            "TLS identity created",
            metadata: ["sha256": "\(created.fingerprintSHA256)", "hostnames": "\(hostnames)", "ips": "\(ipAddresses)", "storage": "\(created.storage.rawValue)"])
        return created
    }

    /// Writes the public certificate and its fingerprint for the shell to pin.
    public func export(to directory: URL) throws {
        try certificateDER.write(to: directory.appending(path: "certificate.der"), options: .atomic)
        try Data((fingerprintSHA256 + "\n").utf8).write(to: directory.appending(path: "fingerprint.sha256"), options: .atomic)
    }

    /// `certificate.der` plus either `private-key.der` or the matching key in
    /// the data-protection keychain. Anything else (a key only in the login
    /// keychain, a stale certificate) means: regenerate.
    static func load(from directory: URL) throws -> TLSIdentity? {
        guard let der = try? Data(contentsOf: directory.appending(path: "certificate.der")),
            let certificate = SecCertificateCreateWithData(nil, der as CFData)
        else { return nil }
        if let keyData = try? Data(contentsOf: directory.appending(path: "private-key.der")) {
            var error: Unmanaged<CFError>?
            guard let key = SecKeyCreateWithData(keyData as CFData, keyAttributes as CFDictionary, &error),
                let identity = SecIdentityCreate(nil, certificate, key)
            else { return nil }
            return TLSIdentity(identity: identity, certificateDER: der, storage: .file)
        }
        let query: [String: Any] = [
            kSecClass as String: kSecClassKey,
            kSecAttrApplicationTag as String: keyTag,
            kSecUseDataProtectionKeychain as String: true,
            kSecReturnRef as String: true,
        ]
        var found: CFTypeRef?
        guard SecItemCopyMatching(query as CFDictionary, &found) == errSecSuccess, let found else { return nil }
        let key = found as! SecKey
        guard let identity = SecIdentityCreate(nil, certificate, key) else { return nil }  // key does not match the certificate
        return TLSIdentity(identity: identity, certificateDER: der, storage: .dataProtectionKeychain)
    }

    /// Removes the key and certificate from the keychains (data-protection and
    /// any login-keychain leftovers of earlier builds) and the exported files.
    public static func reset(directory: URL) {
        for dataProtection in [true, false] {
            var keyQuery: [String: Any] = [kSecClass as String: kSecClassKey, kSecAttrApplicationTag as String: keyTag]
            if dataProtection { keyQuery[kSecUseDataProtectionKeychain as String] = true }
            while SecItemDelete(keyQuery as CFDictionary) == errSecSuccess {}
        }
        let certificateQuery: [String: Any] = [
            kSecClass as String: kSecClassCertificate,
            kSecMatchSubjectContains as String: "\(Attribution.projectName) (",
            kSecMatchLimit as String: kSecMatchLimitAll,
            kSecReturnRef as String: true,
        ]
        var found: CFTypeRef?
        if SecItemCopyMatching(certificateQuery as CFDictionary, &found) == errSecSuccess, let certificates = found as? [SecCertificate] {
            for certificate in certificates {
                let deleteQuery: [String: Any] = [kSecClass as String: kSecClassCertificate, kSecMatchItemList as String: [certificate]]
                SecItemDelete(deleteQuery as CFDictionary)
            }
        }
        for file in ["certificate.der", "fingerprint.sha256", "private-key.der"] {
            try? FileManager.default.removeItem(at: directory.appending(path: file))
        }
    }

    /// Data-protection keychain when the build is entitled to it (signed with a
    /// team identifier), otherwise an in-memory identity whose key lives in a
    /// 0600 file next to the certificate.
    static func create(hostnames: [String], ipAddresses: [String], directory: URL) throws -> TLSIdentity {
        let attributes: [String: Any] = [
            kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
            kSecAttrKeySizeInBits as String: 256,
            kSecAttrLabel as String: label,
            kSecPrivateKeyAttrs as String: [
                kSecAttrIsPermanent as String: true,
                kSecAttrApplicationTag as String: keyTag,
            ],
            kSecUseDataProtectionKeychain as String: true,
        ]
        var error: Unmanaged<CFError>?
        if let privateKey = SecKeyCreateRandomKey(attributes as CFDictionary, &error) {
            let (certificate, der) = try makeCertificate(privateKey: privateKey, hostnames: hostnames, ipAddresses: ipAddresses)
            guard let identity = SecIdentityCreate(nil, certificate, privateKey) else { throw TLSIdentityError.security(errSecInternalError, "create identity") }
            return TLSIdentity(identity: identity, certificateDER: der, storage: .dataProtectionKeychain)
        }
        let ephemeral: [String: Any] = [
            kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
            kSecAttrKeySizeInBits as String: 256,
            kSecPrivateKeyAttrs as String: [kSecAttrIsPermanent as String: false],
        ]
        error = nil
        guard let privateKey = SecKeyCreateRandomKey(ephemeral as CFDictionary, &error) else { throw TLSIdentityError.cf(error!.takeRetainedValue(), "generate key") }
        guard let keyData = SecKeyCopyExternalRepresentation(privateKey, &error) as Data? else { throw TLSIdentityError.cf(error!.takeRetainedValue(), "export key") }
        let (certificate, der) = try makeCertificate(privateKey: privateKey, hostnames: hostnames, ipAddresses: ipAddresses)
        guard let identity = SecIdentityCreate(nil, certificate, privateKey) else { throw TLSIdentityError.security(errSecInternalError, "create identity") }
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: directory.path)
        let keyFile = directory.appending(path: "private-key.der")
        try keyData.write(to: keyFile, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: keyFile.path)
        return TLSIdentity(identity: identity, certificateDER: der, storage: .file)
    }

    /// Self-signed ECDSA P-256 certificate for `privateKey`, ten years, SANs for the given names and addresses.
    static func makeCertificate(privateKey: SecKey, hostnames: [String], ipAddresses: [String]) throws -> (SecCertificate, Data) {
        var error: Unmanaged<CFError>?
        guard let publicKey = SecKeyCopyPublicKey(privateKey),
            let publicData = SecKeyCopyExternalRepresentation(publicKey, &error) as Data?
        else { throw TLSIdentityError.cf(error!.takeRetainedValue(), "export public key") }
        guard publicData.count == 65, publicData.first == 0x04 else { throw TLSIdentityError.invalidKey }

        var serial = (0..<16).map { _ in UInt8.random(in: 0...255) }
        serial[0] &= 0x7F
        let now = Date()
        let template = X509SelfSignedCertificate(
            commonName: "Lanthorn (\(hostnames.first ?? "server"))",
            serialNumber: serial,
            notBefore: now.addingTimeInterval(-300),
            notAfter: now.addingTimeInterval(10 * 365 * 86_400),
            publicKeyX963: Array(publicData),
            dnsNames: hostnames,
            ipAddresses: ipAddresses.compactMap(ipBytes))
        let tbs = Data(template.tbsCertificate())
        guard let signature = SecKeyCreateSignature(privateKey, .ecdsaSignatureMessageX962SHA256, tbs as CFData, &error) as Data?
        else { throw TLSIdentityError.cf(error!.takeRetainedValue(), "sign certificate") }
        let der = Data(template.certificate(signature: Array(signature)))
        guard let certificate = SecCertificateCreateWithData(nil, der as CFData) else {
            throw TLSIdentityError.security(errSecDecode, "parse generated certificate")
        }
        return (certificate, der)
    }

    static func ipBytes(_ text: String) -> [UInt8]? {
        var v4 = in_addr()
        if inet_pton(AF_INET, text, &v4) == 1 { return withUnsafeBytes(of: &v4) { Array($0) } }
        var v6 = in6_addr()
        if inet_pton(AF_INET6, text, &v6) == 1 { return withUnsafeBytes(of: &v6) { Array($0) } }
        return nil
    }
}
